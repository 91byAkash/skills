#!/usr/bin/env bash
# install-hooks.sh - create plain git hooks in .githooks/ and point git at them.
# Usage: install-hooks.sh [--with-pre-push] [--dry-run] [--force]
#   --with-pre-push  also write .githooks/pre-push with the slower test steps
#   --dry-run        print the hooks instead of writing them
#   --force          overwrite existing .githooks/ files
# Detects the stack and writes a pre-commit hook that runs only the steps that
# exist. Linters/formatters run on staged files only; nothing runs when no file
# of that language is staged. Refuses to run next to another hook manager.
set -euo pipefail
with_push=0; dry=0; force=0
for a in "$@"; do
  case "$a" in --with-pre-push) with_push=1 ;; --dry-run) dry=1 ;; --force) force=1 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) echo "unknown option $a" >&2; exit 2 ;; esac
done
git rev-parse --git-dir >/dev/null 2>&1 || { echo "not a git repo" >&2; exit 1; }
root="$(git rev-parse --show-toplevel)"; cd "$root"

existing="$(git config --get core.hooksPath || true)"
for m in .husky .pre-commit-config.yaml lefthook.yml .lefthook.yml; do
  [ -e "$m" ] && { echo "found $m: a hook manager is already set up; extend it instead (see templates/hook-configs.md)" >&2; exit 1; }
done
if [ -n "$existing" ] && [ "$existing" != ".githooks" ]; then
  echo "core.hooksPath is already '$existing'; extend those hooks instead" >&2; exit 1
fi
hookdir="$(git rev-parse --git-path hooks)"   # works in worktrees, where .git is a file
if ls "$hookdir" 2>/dev/null | grep -qv '\.sample$'; then
  echo "note: $hookdir has non-sample hooks ($(ls "$hookdir" | grep -v '\.sample$' | tr '\n' ' ')); they stop running once core.hooksPath is set" >&2
fi

pm=npm
[ -f pnpm-lock.yaml ] && pm=pnpm
[ -f yarn.lock ] && pm=yarn
{ [ -f bun.lockb ] || [ -f bun.lock ]; } && pm=bun

has_script() { [ -f package.json ] && python3 -c 'import json,sys; sys.exit(0 if sys.argv[1] in json.load(open("package.json")).get("scripts",{}) else 1)' "$1"; }

# run CMD on the staged files matching GLOBS, NUL-safe; skip when none are staged
staged_helper='run_on_staged() {  # run_on_staged GLOB... -- CMD ARGS...   (files appended)
  local globs=() files=() f
  while [ "$1" != "--" ]; do globs+=("$1"); shift; done; shift
  while IFS= read -r -d "" f; do files+=("$f"); done < <(git diff --cached --name-only --diff-filter=ACMR -z -- "${globs[@]}")
  [ ${#files[@]} -eq 0 ] && return 0
  "$@" "${files[@]}"
}'

pre=(); push=(); omitted=()
if [ -f package.json ]; then
  if [ -f .lintstagedrc ] || [ -f .lintstagedrc.json ] || grep -q '"lint-staged"' package.json; then pre+=("$pm exec lint-staged"); else omitted+=("staged formatting (no lint-staged config; see templates/hook-configs.md)"); fi
  if has_script lint; then pre+=("$pm run lint"); else omitted+=("lint (no 'lint' script)"); fi
  if has_script typecheck; then pre+=("$pm run typecheck"); else omitted+=("typecheck (no 'typecheck' script)"); fi
  if has_script test; then push+=("$pm test"); else omitted+=("tests (no 'test' script)"); fi
fi
if [ -f pyproject.toml ] || [ -f requirements.txt ]; then
  if command -v ruff >/dev/null 2>&1; then
    pre+=("run_on_staged '*.py' -- ruff check" "run_on_staged '*.py' -- ruff format --check")
  else omitted+=("ruff lint/format (ruff not installed)"); fi
  if python3 -c 'import pytest' 2>/dev/null; then push+=("python3 -m pytest -q"); else omitted+=("pytest (not installed)"); fi
fi
if [ -f go.mod ]; then
  pre+=('out="$(run_on_staged "*.go" -- gofmt -l)"; [ -z "$out" ] || { echo "gofmt needed:"; echo "$out"; exit 1; }' "go vet ./...")
  push+=("go test ./...")
fi
[ ${#pre[@]} -gt 0 ] || pre+=("echo 'no pre-commit steps detected; edit .githooks/pre-commit'")

write_hook() {
  local name="$1"; shift
  local body="#!/usr/bin/env bash
# generated by install-hooks.sh - edit freely
set -euo pipefail
$staged_helper
"
  for c in "$@"; do body+="$c"$'\n'; done
  if [ $dry -eq 1 ]; then printf '%s--- (%s, dry run)\n' "$body" "$name"; return; fi
  if [ -e ".githooks/$name" ] && [ $force -eq 0 ]; then
    echo ".githooks/$name exists; re-run with --force to overwrite" >&2; exit 1
  fi
  mkdir -p .githooks
  printf '%s' "$body" > ".githooks/$name"; chmod +x ".githooks/$name"
  echo "wrote .githooks/$name"
}
write_hook pre-commit "${pre[@]}"
if [ $with_push -eq 1 ]; then
  if [ ${#push[@]} -gt 0 ]; then write_hook pre-push "${push[@]}"; else omitted+=("pre-push (no test command detected)"); fi
fi
for o in "${omitted[@]+"${omitted[@]}"}"; do echo "omitted: $o"; done
if [ $dry -eq 0 ]; then
  git config core.hooksPath .githooks
  echo "set core.hooksPath=.githooks (new clones: run 'git config core.hooksPath .githooks', e.g. from your setup script)"
fi
